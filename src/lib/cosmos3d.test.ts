import { existsSync, readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { cosmosIndex, CosmosError, gridLength, parseCosmosMeta } from './cosmos3d';

const good = {
  source: 'COSMOS',
  source_url: 'https://doi.org/10.26131/IRSA163',
  n_galaxies: 100,
  shape: [2, 3, 4],
  z_near: 0.05,
  z_far: 1.35,
  bounds: { ra_min: 149.4, ra_max: 150.8, dec_min: 1.5, dec_max: 2.9 },
  width_arcmin: 84,
  faint_file: 'cosmos_3d_faint.f32.bin',
  peaks: [
    { ra: 150, dec: 2, z: 1.3, value: 3.1 },
    { ra: 149.9, dec: 2.5, z: 0.7, value: 4.2 },
  ],
};

describe('parseCosmosMeta', () => {
  it('parses metadata and sorts peaks strongest first', () => {
    const m = parseCosmosMeta(good);
    expect(m.shape).toEqual([2, 3, 4]);
    expect(gridLength(m)).toBe(24);
    expect(m.peaks[0].value).toBe(4.2);
    expect(m.faintFile).toBe('cosmos_3d_faint.f32.bin');
  });

  it('uses the prep layout: index = depth + nd * (x + nx * y)', () => {
    const m = parseCosmosMeta(good);
    expect(cosmosIndex(m, 0, 0, 3)).toBe(3);
    expect(cosmosIndex(m, 0, 1, 0)).toBe(4);
    expect(cosmosIndex(m, 1, 0, 0)).toBe(12);
    expect(cosmosIndex(m, 1, 2, 3)).toBe(23);
  });

  it('rejects bad shapes, ranges and file names', () => {
    expect(() => parseCosmosMeta({ ...good, shape: [2, 3] })).toThrow(CosmosError);
    expect(() => parseCosmosMeta({ ...good, z_far: 0 })).toThrow(CosmosError);
    expect(() => parseCosmosMeta({ ...good, bounds: { ...good.bounds, ra_max: 1 } })).toThrow(CosmosError);
    expect(() => parseCosmosMeta({ ...good, faint_file: '../manifest.json' })).toThrow(CosmosError);
    expect(() => parseCosmosMeta({ ...good, peaks: [{ ra: 1 }] })).toThrow(CosmosError);
  });

  it('drops non-https source links', () => {
    expect(parseCosmosMeta({ ...good, source_url: 'javascript:alert(1)' }).sourceUrl).toBe('');
  });

  // data/cosmos is generated by build_data.sh, so this runs only after a build.
  it.skipIf(!existsSync('data/cosmos/cosmos_3d.json'))('accepts the built data file and matches its grid size', () => {
    const raw = JSON.parse(readFileSync('data/cosmos/cosmos_3d.json', 'utf8'));
    const m = parseCosmosMeta(raw);
    expect(readFileSync('data/cosmos/cosmos_3d.f32.bin').byteLength).toBe(gridLength(m) * 4);
    // Sanity check from the prep script: the strongest structure is the known z ~ 0.73 cluster.
    expect(m.peaks[0].z).toBeGreaterThan(0.6);
    expect(m.peaks[0].z).toBeLessThan(0.8);
  });
});
